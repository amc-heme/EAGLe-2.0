# Run from the project root: Rscript tests/check_irf2bp2.R
suppressPackageStartupMessages(source("R/00_libraries.R"))
source("R/01_dataset_config.R")
source("R/module_precomputed.R")
source("R/module_IRF2BP2.R")
local({
  trace("mcfork", where = asNamespace("parallel"), tracer = quote(stop("Fork forbidden by regression test")), print = FALSE)
  on.exit(untrace("mcfork", where = asNamespace("parallel")), add = TRUE)
  config <- load_analysis_config()
  signature <- read_irf2bp2_signature("data/IRF2BP2_signature.tsv")
  stopifnot(length(signature) == 107, !anyDuplicated(signature), all(c("CCL4", "CCL3", "PTGER4") %in% signature))
  objects <- lapply(config[c("T0", "KO_response", "BEAT_quantile", "BEAT_FAB", "BEAT_Denovo.Relapse")],
                    function(entry) load_precomputed_analysis(getwd(), entry))
  original <- readRDS("new_raw_data/BEAT_IRF2BP2_scores.rds")
  for (key in c("BEAT_quantile", "BEAT_FAB", "BEAT_Denovo.Relapse")) {
    result <- calculate_irf2bp2(config[[key]], objects[[key]])
    expected <- original$scores[match(make.names(colnames(objects[[key]])), make.names(names(original$scores)))]
    stopifnot(identical(result$scores$Sample, colnames(objects[[key]])),
              identical(result$scores$IRF2BP2_score, unname(expected)), length(result$matched_genes) == 100)
  }
  # Independently reproduce the original script's symbol averaging and GSVA call on T0.
  raw <- readRDS(paste0(getwd(), config$T0$vst_path))
  annotation <- readRDS(paste0(getwd(), config$T0$path))
  baseline <- data.frame(symbol = toupper(annotation$Gene[match(rownames(raw), annotation$ensembl_gene_id)]),
                         raw, check.names = FALSE)
  baseline <- baseline[!is.na(baseline$symbol) & nzchar(baseline$symbol), ]
  baseline <- baseline %>% dplyr::group_by(symbol) %>%
    dplyr::summarise(dplyr::across(where(is.numeric), mean), .groups = "drop")
  symbols <- baseline$symbol
  baseline <- as.matrix(baseline[, -1])
  rownames(baseline) <- symbols
  baseline <- baseline[apply(baseline, 1, sd) > 0, , drop = FALSE]
  expected <- GSVA::gsva(GSVA::gsvaParam(baseline, list(IRF2BP2 = signature), kcdf = "Gaussian", maxDiff = TRUE),
                         verbose = FALSE, BPPARAM = BiocParallel::SerialParam())
  result <- calculate_irf2bp2(config$T0, objects$T0)
  stopifnot(identical(result$scores$Sample, colnames(raw)), length(result$matched_genes) == 101,
            isTRUE(all.equal(result$scores$IRF2BP2_score, as.numeric(expected["IRF2BP2", ]), tolerance = 1e-12)))
  cat("PASS: exact saved BEAT scores and T0 scores matching the original GSVA method\n")
  key <- reactiveVal("T0")
  choice <- list(user_dataset = reactive(key()))
  object <- reactive(objects[[key()]])
  testServer(IRF2BP2_Server, args = list(dataset_choice = choice, dataset_dds = object,
                                       dataset_config = config, raw_data = getwd()), {
    session$setInputs(group_by = "KO_Sensitivity")
    stopifnot(grepl("Click", output$score_summary), is.null(scored()))
    session$setInputs(calculate = 1)
    stopifnot(nrow(score_data()) == 22, length(unique(score_data()$Group)) == 2,
              grepl("101 of 107", output$score_summary), length(output$score_plot) > 0,
              length(output$score_table) > 0)
    scores <- score_data()$IRF2BP2_score
    session$setInputs(group_by = "Batch")
    stopifnot(identical(scores, score_data()$IRF2BP2_score), length(unique(score_data()$Group)) == 3)
    # Exports are generated by the real Shiny download handlers.
    stopifnot(file.info(output$download_scores)$size > 0, file.info(output$download_plot)$size > 0,
              file.info(output$download_signature)$size > 0)
    key("KO_response")
    session$flushReact()
    stopifnot(is.null(scored()), grepl("Click", output$score_summary))
    session$setInputs(group_by = "Treatment_Sensitivity", calculate = 2)
    stopifnot(nrow(score_data()) == 66, length(unique(score_data()$Group)) == 6,
              all(is.finite(score_data()$IRF2BP2_score)), length(output$score_plot) > 0)
  })
  cat("PASS: T0/KO score plots, grouping, CSV/PNG/signature downloads, and dataset reset\n")
})
